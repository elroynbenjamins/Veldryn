const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const read=x=>fs.readFileSync(path.join(root,x),'utf8');
const sql=read('backend/supabase/migrations/20261104000012_coop_failed_run_consolation_v1.sql');
const projection=read('backend/supabase/migrations/20261104000013_coop_failure_budget_read_v1.sql');
