import assert from 'node:assert/strict';
import {execFile,execFileSync} from 'node:child_process';
import {promisify} from 'node:util';
if(process.env.PGDATABASE!=='scouting_review_ci'||process.env.PGHOST!=='127.0.0.1')throw Error('disposable database only');
const args=['-X','-v','ON_ERROR_STOP=1','-At'];
const q=sql=>execFileSync('psql',[...args,'-c',sql],{encoding:'utf8'}).trim();
const asyncQ=async sql=>(await promisify(execFile)('psql',[...args,'-c',sql])).stdout.trim();
const expectedFailure=async (sql,pattern)=>{try{await asyncQ(sql);assert.fail('expected SQL failure');}catch(e){assert.match(String(e.stderr??e.message),pattern);}};
q("INSERT INTO scouting_qa.account(id,xp,slots) VALUES('a',0,3),('b',0,1); INSERT INTO scouting_qa.character VALUES('a','c1',1000,1000,ARRAY['FROSTMARCH']),('a','c2',2000,1000,ARRAY['GREENFIELDS']),('b','c3',0,1000,ARRAY['GREENFIELDS']); INSERT INTO scouting_qa.character_discovery VALUES('a','c1','green'); INSERT INTO scouting_qa.resource VALUES('a','c1','TRAVEL_RATION',100); INSERT INTO scouting_qa.companion VALUES('a','unit1',false),('a','unit2',false)");
const migrated=await Promise.all(Array.from({length:8},()=>asyncQ("SELECT scouting_qa.migrate('a')")));
assert.deepEqual(migrated,Array(8).fill('3000'));
assert.equal(q("SELECT xp||':'||slots FROM scouting_qa.account WHERE id='a'"),'3000:3');
assert.equal(q("SELECT array_to_string(retained_regions,',') FROM scouting_qa.character WHERE account_id='a' AND id='c2'"),'GREENFIELDS');
q("SELECT scouting_qa.migrate('b')");
const reserve=(nonce,char='c1',ids="ARRAY['unit1']",xp=1800,food=34)=>`SELECT scouting_qa.reserve('a','${char}','${nonce}','camp',NULL,${ids},1000,2000,${xp},300,280,3,${food},2)`;
await expectedFailure(reserve('bad_food1','c1',"ARRAY['unit1']",1800,101),/missing_food/);
assert.equal(q("SELECT gold FROM scouting_qa.character WHERE account_id='a' AND id='c1'"),'1000');
const same=await Promise.all(Array.from({length:8},()=>asyncQ(reserve('camp_001'))));
assert.deepEqual(same,Array(8).fill('camp_001'));
assert.equal(q("SELECT gold FROM scouting_qa.character WHERE account_id='a' AND id='c1'"),'700');
assert.equal(q("SELECT qty FROM scouting_qa.resource WHERE account_id='a' AND character_id='c1'"),'66');
await expectedFailure(reserve('camp_002','c1',"ARRAY['unit2']"),/xp_slot_busy/);
await expectedFailure(reserve('camp_003','c1',"ARRAY['unit1']",0),/companion_unavailable/);
await expectedFailure("SELECT scouting_qa.claim('a','c1','camp_001',1999)",/not_ready/);
await expectedFailure("SELECT scouting_qa.claim('a','c2','camp_001',2000)",/owner_mismatch/);
const claims=await Promise.all(Array.from({length:8},()=>asyncQ("SELECT scouting_qa.claim('a','c1','camp_001',2000)")));
assert.deepEqual(claims,Array(8).fill('1800'));
assert.equal(q("SELECT xp||':'||essence FROM scouting_qa.account WHERE id='a'"),'4800:3');
assert.equal(q("SELECT gold FROM scouting_qa.character WHERE account_id='a' AND id='c1'"),'980');
q("SELECT scouting_qa.reserve('a','c2','route_001','training','green',ARRAY[]::text[],2000,3000,24,0,0,0,0,2)");
assert.equal(q("SELECT scouting_qa.claim('a','c2','route_001',3000)"),'0');
assert.equal(q("SELECT count(*) FROM scouting_qa.character_discovery WHERE account_id='a' AND route_id='green'"),'2');
assert.equal(q("SELECT scouting_qa.migrate('a')"),'4800');
q("CREATE ROLE scouting_guest; GRANT USAGE ON SCHEMA scouting_qa TO scouting_guest");
await expectedFailure("SET ROLE scouting_guest; SELECT * FROM scouting_qa.account",/permission denied/);
await expectedFailure("SET ROLE scouting_guest; SELECT scouting_qa.migrate('a')",/permission denied/);
console.log('PASS disposable PostgreSQL: 8-way migration/reservation/claim, rollback, XP slot, custody, legacy region isolation, no duplicate XP, privileges');
