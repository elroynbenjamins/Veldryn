const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const read=relative=>fs.readFileSync(path.join(__dirname,'..',relative),'utf8');
const screen=read('src/screens/GuildScreen.tsx');
const actions=read('src/components/GuildHomeActions.tsx');
const library=read('src/components/GuildGuideLibrary.tsx');
const overlay=read('src/components/ChatOverlay.tsx');
assert.match(screen,/<GuildGuideLibrary visible={guideLibraryOpen}/,'Guide Library is mounted for online Guild members');
assert.match(screen,/onGuide={\(\)=>setGuideLibraryOpen\(true\)}/,'Home entry actually opens the Guide Library');
assert.match(actions,/title:guideLabel,action:onGuide/,'Guide quick action is available even without the Notice Board');
assert.match(actions,/accessibilityLabel={item.title} onPress={item.action}/,'Quick actions retain an accessible action target');
const tour=read('src/components/GuildTutorialGuide.tsx');
const sectionHelp=read('src/components/SectionGuide.tsx');
assert.match(tour,/onPress={atTarget\?next:open}/,'Tour advances in one tap when player is already at the destination');
assert.match(sectionHelp,/style={styles.dialogScroll}/,'Long help content scrolls within its modal');
assert.match(sectionHelp,/onAccessibilityEscape={close}/,'Section help can be dismissed by accessibility action');
assert.match(library,/guildGuideSectionTitle\(language,id,item.title\)/,'Library sections use localized titles');
assert.match(library,/style={s.libraryScroll}/,'Guide Library is scrollable on smaller screens');
assert.match(library,/group\.leadership\|\|leadership/,'Leadership guide groups are role-gated');
assert.match(library,/accessibilityViewIsModal/,'Guide Library uses modal accessibility semantics');
assert.match(library,/accessibilityRole="tab"/,'Guide topic choices are accessible');
assert.match(library,/localizedGuildDetailedGuide\(language,section\)/,'Library resolves translated detail content');
assert.match(library,/localizedGuildDetailedGuide\(language,id\)/,'Library tiles also resolve translated summaries');
assert.match(screen,/localizedGuildDetailedGuide\(language,guideSection\)/,'Section question-mark help uses the same translation resolver');
assert.match(sectionHelp,/style={styles.dialogScroll}/,'Section help retains responsive scrolling and pinned confirmation');
assert.match(library,/style={s.topicScroll}/,'Guide Library topic details scroll within small screen modal');
assert.match(overlay,/channel==='guild'&&guildHelpOpen/,'Guild Chat help is only shown in Guild Chat');
console.log('PASS Guild Guide library navigation, role gating and Chat guidance UI contracts');
