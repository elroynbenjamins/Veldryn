/** Private sequence tests; no engine event fabrication is trusted in live paths. */
import {strict as assert} from 'node:assert';
import {createEffectEventProvenanceReviewV2,type GemRootOutputReviewV2} from '../effect-gem-event-provenance-review';
import type {reviewFrozenForgeSocketsV2} from '../frozen-forge-socket-review';
type Projection=ReturnType<typeof reviewFrozenForgeSocketsV2>;
export function runEffectEventProvenanceReviewV2(support:Projection,damage:Projection){
 const ledger=createEffectEventProvenanceReviewV2([{actorId:'support',projection:support},{actorId:'damage',projection:damage}]);
 const root=(id:string,actorId='support',origin:'authored'|'basic'|'companion'='authored',category:'support'|'offense'='support')=>
  ledger.registerAction({id,actorId,origin,category,at:0});
 const out=(id:string,actionId:string,targetId:string,kind:GemRootOutputReviewV2['kind'],overrides:Partial<GemRootOutputReviewV2>={})=>
  ledger.registerOutput({id,actionId,targetId,kind,at:0,timing:'direct',successful:true,actual:50,attempted:100,targetMaxHp:1000,targetShield:0,...overrides});
 const supportGroup=(id:string)=>support.effectResonanceReview!.families.find(g=>g.familyId===id)!;
 const damageGroup=(id:string)=>damage.effectResonanceReview!.families.find(g=>g.familyId===id)!;
 const max=damage.stats.maxHp;
 const recovery={hp:max*.5,shield:0};
 const mercyAmount=50*supportGroup('effect_mercy').totalValue;
 const renewGroup=supportGroup('effect_renewal');
 const renewAmount=50*renewGroup.totalValue*(renewGroup.resonance>=2?1.2:1)/(renewGroup.resonance>=2?3:2);
 root('heal');
 out('heal-a','heal','ally-a','heal');
 out('heal-a-duplicate','heal','ally-a','heal');
 out('heal-b','heal','ally-b','heal');
 assert.equal(ledger.claim('effect_benediction','heal-a').accepted,true);
 assert.equal(ledger.claim('effect_benediction','heal-b').accepted,false);
 assert.equal(ledger.claim('effect_mercy','heal-a').accepted,true);
 assert.equal(ledger.claim('effect_mercy','heal-a-duplicate').accepted,false);
 assert.equal(ledger.claim('effect_mercy','heal-b').accepted,true);
 assert.equal(ledger.claim('effect_renewal','heal-a').accepted,true);
 assert.equal(ledger.claim('effect_renewal','heal-b').accepted,true);
 assert.throws(()=>ledger.emitSecondary('effect_mercy','heal-a','oversized','barrier',0,'ally-a',mercyAmount+1),/secondary_magnitude/);
 const barrier=ledger.emitSecondary('effect_mercy','heal-a','mercy-a','barrier',0,'ally-a',mercyAmount);
 assert.equal(barrier.mayTriggerEffects,false);
 assert.equal(ledger.claim('effect_guardians_gift','mercy-a').accepted,false);
 assert.equal(ledger.claim('effect_shared_resolve','mercy-a').accepted,false);
 assert.throws(()=>ledger.emitSecondary('effect_mercy','heal-a','mercy-copy','barrier',0,'ally-a',10),/duplicate_secondary/);
 assert.throws(()=>ledger.emitSecondary('effect_mercy','heal-a-duplicate','fake','barrier',0,'ally-a',10),/secondary/);
 assert.throws(()=>ledger.emitSecondary('effect_mercy','heal-b','foreign','barrier',0,'ally-a',10),/secondary_target/);
 assert.throws(()=>ledger.emitSecondary('effect_renewal','heal-a','renew-over','heal',2000,'ally-a',renewAmount+1,1),/secondary_magnitude/);
 if(renewGroup.resonance===1)assert.throws(()=>ledger.emitSecondary('effect_renewal','heal-a','renew-third','heal',6000,'ally-a',renewAmount,3),/renewal_tick/);
 const renew=ledger.emitSecondary('effect_renewal','heal-a','renew-a1','heal',2000,'ally-a',renewAmount,1);
 assert.equal(renew.depth,1);
 for(const family of ['effect_mercy','effect_renewal','effect_benediction'] as const)assert.equal(ledger.claim(family,'renew-a1').accepted,false);
 assert.throws(()=>ledger.emitSecondary('effect_renewal','heal-a','renew-repeat','heal',2000,'ally-a',5,1),/duplicate_secondary/);
 assert.throws(()=>ledger.emitSecondary('effect_renewal','heal-a','renew-early','heal',3000,'ally-a',5,2),/renewal_tick/);
 root('shield');
 out('shield-a','shield','ally-a','barrier');
 out('shield-b','shield','ally-b','barrier');
 assert.equal(ledger.claim('effect_shared_resolve','shield-a').accepted,true);
 assert.equal(ledger.claim('effect_shared_resolve','shield-b').accepted,false);
 assert.equal(ledger.claim('effect_guardians_gift','shield-a').accepted,true);
 assert.equal(ledger.claim('effect_guardians_gift','shield-b').accepted,true);
 root('dot');
 out('hot','dot','ally-a','heal',{timing:'periodic'});
 assert.equal(ledger.claim('effect_mercy','hot').accepted,false);
 assert.equal(ledger.claim('effect_renewal','hot').accepted,false);
 root('comp','support','companion');
 out('comp-heal','comp','ally-a','heal');
 assert.equal(ledger.claim('effect_mercy','comp-heal').accepted,false);
 root('hit','damage','authored','offense');
 out('hit-miss','hit','enemy-a','damage',{successful:false,actual:0});
 out('hit-a','hit','enemy-a','damage',{critical:true});
 out('hit-b','hit','enemy-b','damage',{critical:true});
 assert.equal(ledger.claim('effect_momentum','hit-miss').accepted,false);
 assert.equal(ledger.claim('effect_momentum','hit-a').accepted,true);
 assert.equal(ledger.claim('effect_momentum','hit-b').accepted,false);
 assert.equal(ledger.claim('effect_critical_surge','hit-a').accepted,true);
 assert.equal(ledger.claim('effect_critical_surge','hit-b').accepted,false);
 assert.equal(ledger.claim('effect_retaliation','hit-a',recovery).accepted,false);
 assert.equal(ledger.registerRetaliationDamage('damage',0,max*.01,true,true),false);
 assert.equal(ledger.registerRetaliationDamage('damage',0,max*.12,true,true),true);
 assert.equal(ledger.claim('effect_retaliation','hit-a',recovery).accepted,true);
 assert.equal(ledger.claim('effect_retaliation','hit-b',recovery).accepted,false);
 assert.throws(()=>ledger.emitSecondary('effect_retaliation','hit-a','retaliation-over','heal',0,'damage',max*.02),/secondary_magnitude/);
 ledger.emitSecondary('effect_retaliation','hit-a','retaliation-heal','heal',0,'damage',max*.01);
 assert.equal(ledger.claim('effect_sustenance','retaliation-heal').accepted,false);
 root('basic','damage','basic','offense');
 out('basic-hit','basic','enemy-a','damage');
 assert.equal(ledger.claim('effect_retaliation','basic-hit').accepted,false);
 root('kill','damage','authored','offense');
 out('kill-a','kill','enemy-a','kill',{actual:1,attempted:1});
 assert.equal(ledger.claim('effect_sustenance','kill-a',recovery).accepted,true);
 const sustainAmount=max*damageGroup('effect_sustenance').totalValue;
 assert.throws(()=>ledger.emitSecondary('effect_sustenance','kill-a','sustain-over','heal',0,'damage',sustainAmount+1),/secondary_magnitude/);
 ledger.emitSecondary('effect_sustenance','kill-a','sustain-heal','heal',0,'damage',sustainAmount);
 assert.throws(()=>out('kill-replay','kill','enemy-a','kill',{actual:1,attempted:1}),/duplicate_kill/);
 out('kill-b','kill','enemy-b','kill',{actual:1,attempted:1});
 assert.equal(ledger.claim('effect_sustenance','kill-b',recovery).accepted,false);
 assert.equal(ledger.claim('effect_sustenance','sustain-heal').accepted,false);
 assert.throws(()=>ledger.emitSecondary('effect_sustenance','sustain-heal','recursive','heal',0,'damage',1),/secondary/);
 assert.throws(()=>out('mercy-a','heal','ally-a','barrier'),/output/);
 assert.throws(()=>root('heal'),/action/);
 assert.throws(()=>out('unknown','missing','ally-a','heal'),/output/);
 const result=ledger.inspect();
 assert.equal(result.terminalEvents,4);
 assert.equal(result.canExecuteEffects,false);
 return result;
}
