-- Party Events v12 canonical source regression.
-- Run after v11 and v12 migrations; everything rolls back.
-- No production enrollment, source, credits or rewards are affected.
begin;
do $$
declare
 a uuid[]:=array[gen_random_uuid(),gen_random_uuid(),gen_random_uuid()];
 c uuid[]:=array[gen_random_uuid(),gen_random_uuid(),gen_random_uuid()];
 p uuid:=gen_random_uuid();
 run_ok uuid:=gen_random_uuid();
 run_solo uuid:=gen_random_uuid();
 craft_id uuid:=gen_random_uuid();
 craft_final uuid:=gen_random_uuid();
 crafted_unsupported uuid:=gen_random_uuid();
 start_at timestamptz:=(date_trunc('week',now() at time zone 'UTC') at time zone 'UTC');
 context_hash text:=repeat('c',64);
 first_result jsonb;
 replay_result jsonb;
 combat_result jsonb;
 finale_result jsonb;
 i integer;
begin
 if has_table_privilege('service_role','private.party_event_sources_v11','insert')
   or has_table_privilege('authenticated','private.party_event_sources_v11','insert')
   or has_table_privilege('anon','private.party_event_sources_v11','select')
 then raise exception 'V12 source fabrication grant exists';end if;
 if has_function_privilege('authenticated','private.record_party_event_canonical_action_v12(uuid,timestamptz,text,uuid,text,uuid,text,text,text)','execute')
   or not has_function_privilege('service_role','private.record_party_event_canonical_action_v12(uuid,timestamptz,text,uuid,text,uuid,text,text,text)','execute')
 then raise exception 'V12 canonical bridge permissions incorrect';end if;

 for i in 1..3 loop
  insert into auth.users(id,email)
   values(a[i],'party-v12-'||a[i]||'@example.invalid');
  insert into public.characters(id,account_id,name,class_id)
   values(c[i],a[i],'Adventure Tester '||chr(64+i),
    case i when 1 then 'IRONWARDEN' when 2 then 'WAYFINDER'
    else 'RAVAGER' end);
 end loop;
 insert into public.parties(id,leader_account_id,leader_character_id)
 values(p,a[1],c[1]);
 insert into private.party_event_weeks_v11(
  party_id,event_starts_at,event_ends_at,family,variation,seed,difficulty)
 values(p,start_at,start_at+interval '7 days',
  'broken_caravan','bandits_crossing',0,'standard');
 insert into private.party_event_roster_v11(
  party_id,event_starts_at,account_id,character_id,role,joined_at)
 values(p,start_at,a[1],c[1],'tank',start_at),
       (p,start_at,a[2],c[2],'damage',start_at);

 insert into private.party_event_stages_v11(party_id,event_starts_at,stage,opened_at)
 values(p,start_at,1,start_at);
 update private.party_event_weeks_v11 set active_stage=2
  where party_id=p and event_starts_at=start_at;
 insert into private.party_event_stages_v11(party_id,event_starts_at,stage,opened_at)
 values(p,start_at,2,now()-interval '2 seconds');
 update private.party_event_stages_v11
  set vote_choice='safe_pass',vote_locked_at=now()-interval '1 second'
  where party_id=p and event_starts_at=start_at and stage=2;

 -- Supported craft receipt: generated by the existing crafting server path.
 insert into public.craft_receipts(
   receipt_id,character_id,idempotency_key,recipe_id,quantity)
 values(craft_id,c[1],'v12-craft-canonical-01','SMELT_COPPER_INGOT',1);
 first_result:=private.record_party_event_canonical_action_v12(
   p,start_at,'craft',craft_id,null,null,
   'support_expedition','v12-request-craft-01',context_hash);
 if first_result->>'replayed'<>'false' or
   (first_result->>'eventPointsGranted')::integer<>0
 then raise exception 'V12 canonical craft not admitted once with zero EP';end if;
 replay_result:=private.record_party_event_canonical_action_v12(
   p,start_at,'craft',craft_id,null,null,
   'support_expedition','v12-request-craft-01',context_hash);
 if replay_result->>'replayed'<>'true'
   or replay_result->>'receiptId'<>first_result->>'receiptId'
 then raise exception 'V12 exact craft replay was not idempotent';end if;
 begin
  perform private.record_party_event_canonical_action_v12(
    p,start_at,'craft',craft_id,null,null,
    'support_expedition','v12-request-craft-02',context_hash);
  raise exception 'V12 second request reused the same craft';
 exception when others then
  if sqlerrm<>'party_event_action_already_claimed' then raise;end if;
 end;
 begin
  perform private.record_party_event_canonical_action_v12(
    p,start_at,'craft',craft_id,null,null,
    'scout_route','v12-request-craft-03',context_hash);
  raise exception 'V12 crafting wrongly credited scouting';
 exception when others then
  if sqlerrm<>'party_event_v12_wrong_source_for_action' then raise;end if;
 end;
 begin
  perform private.record_party_event_canonical_action_v12(
    p,start_at,'craft',gen_random_uuid(),null,null,
    'prepare_finale','v12-request-craft-04',context_hash);
  raise exception 'V12 fake receipt was accepted';
 exception when others then
  if sqlerrm<>'party_event_v12_missing_canonical_craft' then raise;end if;
 end;
 insert into public.craft_receipts(
  receipt_id,character_id,idempotency_key,recipe_id,quantity)
 values(crafted_unsupported,c[1],'v12-craft-unsupported-01',
   'UNKNOWN_TEST_CRAFT_RECIPE',1);
 begin
  perform private.record_party_event_canonical_action_v12(
    p,start_at,'craft',crafted_unsupported,null,null,
    'support_expedition','v12-request-craft-05',context_hash);
  raise exception 'V12 unsupported recipe was accepted';
 exception when others then
  if sqlerrm<>'party_event_v12_missing_canonical_craft' then raise;end if;
 end;

 insert into public.expedition_runs(
  id,expedition_id,tier,content_version,seed_hash,created_by,
  coop_mode,phase,route_graph_json)
 values(
  run_ok,'EXP_001',1,'v12-test','v12-test',a[1],
  'live','awaiting_choice',
  '{"nodes":[{"nodeId":"elite-one","contentId":"ROOTBOUND_ELITE_01","depth":1,"kind":"elite"},{"nodeId":"chest-one","contentId":"UNKNOWN_CHEST","depth":2,"kind":"merchant"},{"nodeId":"elite-failed","contentId":"ROOTBOUND_ELITE_01","depth":3,"kind":"elite"}]}'::jsonb
 );
 for i in 1..2 loop
  insert into public.expedition_run_members(
   run_id,character_id,account_id,role,synced_level,
   loadout_snapshot,stat_snapshot,member_kind,active_participant_account_id)
  values(run_ok,c[i],a[i],
   case i when 1 then 'tank' else 'damage' end,25,
   '{}'::jsonb,'{}'::jsonb,'human',a[i]);
  insert into public.coop_run_access_memberships(
   run_id,account_id,membership_kind,channel_epoch)
  values(run_ok,a[i],'live_participant',1);
 end loop;
 insert into public.coop_node_results(
  run_id,node_id,fencing_generation,success,start_state_hash,result_json,end_state_json)
 values(run_ok,'elite-one',1,true,'v12-hash','{}','{}'),
       (run_ok,'elite-failed',1,false,'v12-hash','{}','{}'),
       (run_ok,'chest-one',1,true,'v12-hash','{}','{}');

 combat_result:=private.record_party_event_canonical_action_v12(
  p,start_at,'coop_node',run_ok,'elite-one',a[2],
  'secure_approach','v12-request-combat-01',context_hash);
 if combat_result->>'replayed'<>'false' or
  (combat_result->>'eventPointsGranted')::integer<>0
 then raise exception 'V12 valid shared combat not credited exactly once';end if;
 replay_result:=private.record_party_event_canonical_action_v12(
  p,start_at,'coop_node',run_ok,'elite-one',a[2],
  'secure_approach','v12-request-combat-01',context_hash);
 if replay_result->>'replayed'<>'true'
  or replay_result->>'receiptId'<>combat_result->>'receiptId'
 then raise exception 'V12 combat replay broken';end if;
 begin
  perform private.record_party_event_canonical_action_v12(
   p,start_at,'coop_node',run_ok,'elite-one',a[1],
   'secure_approach','v12-request-combat-01',context_hash);
  raise exception 'V12 duplicate request ID accepted for a different member';
 exception when others then
  if sqlerrm<>'party_event_source_or_request_reused' then raise;end if;
 end;
 replay_result:=private.record_party_event_canonical_action_v12(
  p,start_at,'coop_node',run_ok,'elite-one',a[1],
  'secure_approach','v12-request-combat-other',context_hash);
 if replay_result->>'replayed'<>'false'
  or replay_result->>'receiptId'=combat_result->>'receiptId'
 then raise exception 'V12 legitimate second party member was not credited independently';end if;
 begin
  perform private.record_party_event_canonical_action_v12(
   p,start_at,'coop_node',run_ok,'elite-failed',a[2],
   'secure_approach','v12-request-combat-02',context_hash);
  raise exception 'V12 failed fight accepted';
 exception when others then
  if sqlerrm<>'party_event_v12_missing_canonical_combat' then raise;end if;
 end;
 begin
  perform private.record_party_event_canonical_action_v12(
   p,start_at,'coop_node',run_ok,'chest-one',a[2],
   'secure_approach','v12-request-combat-03',context_hash);
  raise exception 'V12 merchant node accepted as combat';
 exception when others then
  if sqlerrm<>'party_event_v12_missing_canonical_combat' then raise;end if;
 end;
 begin
  perform private.record_party_event_canonical_action_v12(
   p,start_at,'coop_node',run_ok,'elite-one',a[3],
   'secure_approach','v12-request-combat-04',context_hash);
  raise exception 'V12 outsider forged a combat participant';
 exception when others then
  if sqlerrm<>'party_event_v12_missing_canonical_combat' then raise;end if;
 end;

 -- One human participant is not cooperative activity, even if it won.
 insert into public.expedition_runs(
  id,expedition_id,tier,content_version,seed_hash,created_by,
  coop_mode,phase,route_graph_json)
 values(run_solo,'EXP_001',1,'v12-test','v12-test',a[1],
  'live','awaiting_choice',
  '{"nodes":[{"nodeId":"solo-elite","contentId":"ROOTBOUND_ELITE_01","depth":1,"kind":"elite"}]}'::jsonb);
 insert into public.expedition_run_members(
  run_id,character_id,account_id,role,synced_level,
  loadout_snapshot,stat_snapshot,member_kind,active_participant_account_id)
 values(run_solo,c[1],a[1],'tank',25,'{}','{}','human',a[1]);
 insert into public.coop_run_access_memberships(
  run_id,account_id,membership_kind,channel_epoch)
 values(run_solo,a[1],'live_participant',1);
 insert into public.coop_node_results(
  run_id,node_id,fencing_generation,success,start_state_hash,result_json,end_state_json)
 values(run_solo,'solo-elite',1,true,'v12-hash','{}','{}');
 begin
  perform private.record_party_event_canonical_action_v12(
   p,start_at,'coop_node',run_solo,'solo-elite',a[1],
   'secure_approach','v12-request-combat-05',context_hash);
  raise exception 'V12 solo node accepted as party event encounter';
 exception when others then
  if sqlerrm<>'party_event_v12_not_a_party_encounter' then raise;end if;
 end;

 -- Stage 3 requires its own frozen vote and a new canonical craft receipt.
 update private.party_event_weeks_v11 set active_stage=3
 where party_id=p and event_starts_at=start_at;
 insert into private.party_event_stages_v11(party_id,event_starts_at,stage,opened_at)
 values(p,start_at,3,now()-interval '0.5 seconds');
 update private.party_event_stages_v11
  set vote_choice='brace_wagons',vote_locked_at=now()
  where party_id=p and event_starts_at=start_at and stage=3;
 insert into public.craft_receipts(
  receipt_id,character_id,idempotency_key,recipe_id,quantity)
 values(craft_final,c[2],'v12-craft-final-01','SMELT_COPPER_INGOT',1);
 finale_result:=private.record_party_event_canonical_action_v12(
  p,start_at,'craft',craft_final,null,null,
  'prepare_finale','v12-request-final-01',context_hash);
 if finale_result->>'replayed'<>'false' then
  raise exception 'V12 final craft preparation rejected';end if;
 if (select count(*) from private.party_event_sources_v11
   where party_id=p and event_starts_at=start_at)<>4
   or (select count(*) from private.party_event_receipts_v11
     where party_id=p and event_starts_at=start_at)<>4
   or exists(select 1 from private.party_event_receipts_v11
     where party_id=p and event_points_awarded<>0)
 then raise exception 'V12 source-to-receipt ratio or zero-EP invariant broken';end if;

 -- Co-op access is revoked when the run ends. Exact retries must still
 -- replay the persisted, once-verified receipt (even after event close).
 update public.coop_run_access_memberships set active=false where run_id=run_ok;
 update private.party_event_weeks_v11 set status='closed'
  where party_id=p and event_starts_at=start_at;
 replay_result:=private.record_party_event_canonical_action_v12(
  p,start_at,'coop_node',run_ok,'elite-one',a[2],
  'secure_approach','v12-request-combat-01',context_hash);
 if replay_result->>'replayed'<>'true'
  or replay_result->>'receiptId'<>combat_result->>'receiptId'
 then raise exception 'V12 replay fails after run/member/event close';end if;
 begin
  perform private.record_party_event_canonical_action_v12(
   p,start_at,'coop_node',run_ok,'elite-one',a[2],
   'secure_approach','v12-request-combat-new-after-close',context_hash);
  raise exception 'V12 new request accepted after closure';
 exception when others then
  if sqlerrm not in ('party_event_v12_missing_canonical_combat','party_event_window_closed',
     'party_event_action_already_claimed')
  then raise;end if;
 end;
end $;
select 'PASS: V12 canonical craft and co-op sources, role and source attestation, replay, zero EP' as result;
rollback;
