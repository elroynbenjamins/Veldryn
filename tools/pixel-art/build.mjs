// Builds every generated pixel-art asset used by the gathering scenes and combat effects.
//
//   node tools/pixel-art/build.mjs            regenerate assets + the typed manifest
//   node tools/pixel-art/build.mjs --check    fail if the committed output is stale
//
// One art pixel is drawn at PIXEL_UNIT dp. Sheets are exported at 1x/2x/3x with
// nearest-neighbour scaling, so React Native picks a file whose pixels map 1:1 onto the
// device grid and the art stays sharp without any runtime filtering.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {sheet} from './canvas.mjs';
import {miningFrames,choppingFrames,fishingFrames} from './gatherer.mjs';
import {BIOMES,CAVE_CRYSTALS,ORES,ROCK,SCENE,TREE,WOODS,caveBackground,forestBackground,logPiece,oreChunk,oreRock,rippleFrames,splashFrames,tree,watersideBackground} from './scenes.mjs';
import {FX_SHEETS,arrow} from './fx.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const assetDir=path.join(root,'apps/mobile/assets/pixel-scenes-v1');
const manifestPath=path.join(root,'apps/mobile/src/theme/pixel-scene-assets.ts');
const check=process.argv.includes('--check');
const PIXEL_UNIT=2;
const DENSITIES=[[1,''],[2,'@2x'],[3,'@3x']];

const outputs=new Map();
function emit(name,canvas){
  for(const [density,suffix] of DENSITIES)outputs.set(`${name}${suffix}.png`,canvas.scaled(PIXEL_UNIT*density).png());
  return `require('../../assets/pixel-scenes-v1/${name}.png')`;
}
const kebab=id=>id.toLowerCase().replaceAll('_','-');
const lines=[];
const push=line=>lines.push(line);

// ------------------------------------------------------------------ gatherer
const mine=miningFrames(),chop=choppingFrames(),fishing=fishingFrames();
const clip=(name,frames,durationsMs,frame,extra='')=>`{source:${emit(name,sheet(frames))},frameWidth:${frame.width},frameHeight:${frame.height},frames:${frames.length},durationsMs:[${durationsMs.join(',')}]${extra}}`;

// Scene layout, in art pixels. The swing sheets put the feet on the ground line and the
// tool's strike point on the node; the numbers below are derived from the drawn frames.
const FEET_ROW=37,groundY=SCENE.ground;
const swingLeft=64,swingTop=groundY-FEET_ROW;
const rockLeft=swingLeft+mine.contact[0]-2,rockTop=groundY+1-ROCK.height;
const treeLeft=swingLeft+chop.contact[0]-TREE.trunkLeft-1,treeTop=groundY+1-TREE.height;
const bankTop=40,fishLeft=52,fishTop=bankTop-FEET_ROW;

push(`// GENERATED by tools/pixel-art/build.mjs. Do not edit by hand; edit the generator and rebuild.`);
push(`// All coordinates are in art pixels. Multiply by PIXEL_UNIT for density-independent pixels.`);
push(`import type {ImageSourcePropType} from 'react-native';`);
push(``);
push(`export interface PixelSpriteSheet{source:ImageSourcePropType;frameWidth:number;frameHeight:number;frames:number;durationsMs:readonly number[];}`);
push(`export interface PixelFxSheet{tint:ImageSourcePropType;core:ImageSourcePropType;frameSize:number;frames:number;}`);
push(`export type PixelBiome='asterfall'|'sunscar'|'frostmarch'|'ashlands';`);
push(``);
push(`export const PIXEL_UNIT=${PIXEL_UNIT};`);
push(`export const PIXEL_SCENE={width:${SCENE.width},height:${SCENE.height},ground:${groundY}} as const;`);
push(``);
push(`export const GATHERER_SHEETS={`);
push(`  mining:${clip('gatherer-mine',mine.frames,mine.durationsMs,mine.frame,`,impactFrame:${mine.impactFrame}`)},`);
push(`  woodcutting:${clip('gatherer-chop',chop.frames,chop.durationsMs,chop.frame,`,impactFrame:${chop.impactFrame}`)},`);
push(`  fishingCast:${clip('gatherer-fish-cast',fishing.cast.frames,fishing.cast.durationsMs,fishing.frame)},`);
push(`  fishingWait:${clip('gatherer-fish-wait',fishing.wait.frames,fishing.wait.durationsMs,fishing.frame)},`);
push(`  fishingPull:${clip('gatherer-fish-pull',fishing.pull.frames,fishing.pull.durationsMs,fishing.frame)},`);
push(`} as const;`);
push(``);
push(`export const GATHERING_LAYOUT={`);
push(`  swing:{left:${swingLeft},top:${swingTop}},`);
push(`  miningContact:{x:${swingLeft+mine.contact[0]},y:${swingTop+mine.contact[1]}},`);
push(`  choppingContact:{x:${swingLeft+chop.contact[0]},y:${swingTop+chop.contact[1]}},`);
push(`  rock:{left:${rockLeft},top:${rockTop},width:${ROCK.width},height:${ROCK.height}},`);
push(`  tree:{left:${treeLeft},top:${treeTop},width:${TREE.width},height:${TREE.height}},`);
push(`  fishing:{left:${fishLeft},top:${fishTop}},`);
push(`  bobber:{x:${fishLeft+fishing.bobber[0]},y:${fishTop+fishing.bobber[1]}},`);
push(`  waterTop:28,`);
push(`  caveLamp:{x:40,y:30},`);
push(`  caveCrystals:[${CAVE_CRYSTALS.map(([x,y])=>`{x:${x},y:${y-3}}`).join(',')}],`);
push(`} as const;`);
push(``);

// ------------------------------------------------------------------ backgrounds
const biomes=Object.keys(BIOMES);
push(`export const SCENE_BACKGROUNDS:Record<'cave'|'forest'|'water',Record<PixelBiome,ImageSourcePropType>>={`);
push(`  cave:{${biomes.map(b=>`${b}:${emit(`bg-cave-${b}`,caveBackground(b))}`).join(',')}},`);
push(`  forest:{${biomes.map(b=>`${b}:${emit(`bg-forest-${b}`,forestBackground(b))}`).join(',')}},`);
push(`  water:{${biomes.map(b=>`${b}:${emit(`bg-water-${b}`,watersideBackground(b))}`).join(',')}},`);
push(`};`);
push(`/** Underground pools (for example the Old Mines) fish against a cave wall instead of open sky. */`);
push(`export const CAVE_POOL_BACKGROUND:ImageSourcePropType=${emit('bg-water-cave',watersideBackground('asterfall',true))};`);
push(``);
push(`/** Small flat-colour particles are drawn as art-pixel squares in these palette colours. */`);
push(`export const BIOME_PARTICLES:Record<PixelBiome,{dust:string;glint:string;glintLight:string;leaf:string;waterLight:string;ambient:'motes'|'snow'|'embers'|'sand'}>={`);
for(const b of biomes){
  const p=BIOMES[b],ambient=b==='frostmarch'?'snow':b==='ashlands'?'embers':b==='sunscar'?'sand':'motes';
  push(`  ${b}:{dust:'${p.cave.floorLight}',glint:'${p.cave.crystal}',glintLight:'${p.cave.crystalLight}',leaf:'${p.wood.leaf}',waterLight:'${p.water.waterLight}',ambient:'${ambient}'},`);
}
push(`};`);
push(``);

// ------------------------------------------------------------------ nodes
push(`export const ORE_NODES:Record<string,{biome:PixelBiome;rock:ImageSourcePropType;chunk:ImageSourcePropType;spark:string;sparkLight:string;fragment:string}>={`);
const rockFragment={asterfall:'#69727f',sunscar:'#b07f54',frostmarch:'#9dbdd3',ashlands:'#4c3c3c'};
for(const [id,ore] of Object.entries(ORES))push(`  ${id}:{biome:'${ore.biome}',rock:${emit(`rock-${kebab(id)}`,oreRock(id))},chunk:${emit(`chunk-${kebab(id)}`,oreChunk(id))},spark:'${ore.ore}',sparkLight:'${ore.oreLight}',fragment:'${rockFragment[ore.biome]}'},`);
push(`};`);
push(`export const WOOD_NODES:Record<string,{biome:PixelBiome;tree:ImageSourcePropType;log:ImageSourcePropType;chip:string;chipLight:string;leaf:string}>={`);
for(const [id,wood] of Object.entries(WOODS))push(`  ${id}:{biome:'${wood.biome}',tree:${emit(`tree-${kebab(id)}`,tree(id))},log:${emit(`log-${kebab(id)}`,logPiece(id))},chip:'${wood.bark}',chipLight:'${wood.wood}',leaf:'${wood.leaf}'},`);
push(`};`);
push(`export const CHUNK_SIZE={width:10,height:10} as const;`);
push(`export const LOG_SIZE={width:13,height:9} as const;`);
push(``);

// ------------------------------------------------------------------ water effects
const ripple=rippleFrames(),splash=splashFrames();
push(`export const WATER_FX={`);
push(`  ripple:${clip('fx-ripple',ripple,[260,260,260,300],{width:ripple[0].width,height:ripple[0].height})},`);
push(`  splash:${clip('fx-splash',splash,[90,110,130,150],{width:splash[0].width,height:splash[0].height})},`);
push(`} as const;`);
push(``);

// ------------------------------------------------------------------ combat effects
push(`/** White two-layer effect sheets: \`tint\` takes the theme accent, \`core\` stays white. */`);
push(`export const COMBAT_FX:Record<${Object.keys(FX_SHEETS).map(name=>`'${name}'`).join('|')},PixelFxSheet>={`);
for(const [name,painter] of Object.entries(FX_SHEETS)){
  const frames=painter();
  push(`  ${name}:{tint:${emit(`fx-${name}-tint`,sheet(frames.map(f=>f.tint)))},core:${emit(`fx-${name}-core`,sheet(frames.map(f=>f.core)))},frameSize:${frames[0].tint.width},frames:${frames.length}},`);
}
push(`};`);
const arrowSprite=arrow();
push(`export const COMBAT_ARROW={source:${emit('fx-arrow',arrowSprite)} as ImageSourcePropType,width:${arrowSprite.width},height:${arrowSprite.height}} as const;`);
push(``);

const manifest=lines.join('\n');
if(check){
  const stale=[];
  for(const [name,buffer] of outputs){
    const file=path.join(assetDir,name);
    if(!fs.existsSync(file)||!fs.readFileSync(file).equals(buffer))stale.push(name);
  }
  const existing=fs.existsSync(assetDir)?fs.readdirSync(assetDir).filter(name=>name.endsWith('.png')):[];
  const orphaned=existing.filter(name=>!outputs.has(name));
  if(!fs.existsSync(manifestPath)||fs.readFileSync(manifestPath,'utf8')!==manifest)stale.push('pixel-scene-assets.ts');
  if(stale.length||orphaned.length){
    console.error(`Pixel-art output is stale. Run: node tools/pixel-art/build.mjs\n${[...stale.map(n=>'stale: '+n),...orphaned.map(n=>'orphaned: '+n)].join('\n')}`);
    process.exit(1);
  }
  console.log(`PASS: ${outputs.size} generated pixel-art files and the manifest are up to date`);
}else{
  fs.mkdirSync(assetDir,{recursive:true});
  for(const name of fs.readdirSync(assetDir))if(name.endsWith('.png')&&!outputs.has(name))fs.rmSync(path.join(assetDir,name));
  let bytes=0;
  for(const [name,buffer] of outputs){fs.writeFileSync(path.join(assetDir,name),buffer);bytes+=buffer.length;}
  fs.writeFileSync(manifestPath,manifest);
  console.log(`Wrote ${outputs.size} files (${(bytes/1024).toFixed(0)} KiB) to ${path.relative(root,assetDir)} and ${path.relative(root,manifestPath)}`);
}
