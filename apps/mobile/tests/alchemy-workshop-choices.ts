import {assert} from './test-assert';
import {ALCHEMY_RECIPES,potionDef,POTIONS} from '../src/content/alchemy';
import type {Recipe} from '../src/content/skills';
import {alchemyPotionRows} from '../src/core/alchemy-workshop-choices';

const candidates=ALCHEMY_RECIPES.filter(recipe=>!!potionDef(recipe.output.itemId)) as Recipe[];
const unavailable=()=>0;
const all=alchemyPotionRows(candidates,unavailable,60);
assert.equal(all.length,POTIONS.length,'a single row per heal, damage, defense and support potion');
assert.equal(new Set(all.map(row=>row.outputId)).size,12,'regional variants never render duplicate potion rows');
const outputId='GREATER_VIGOR_TONIC';
const base='BREW_GREATER_VIGOR_TONIC',alternate='BREW_GREATER_VIGOR_TONIC_SUNSCAR';
const matching=all.find(row=>row.outputId===outputId)!;
assert.equal(matching.options.length,2,'regional tonic retains both brewing ingredient recipes');
assert.equal(matching.recipe.id,base,'original recipe is the default when neither option is craftable');
const bothAvailable=alchemyPotionRows(candidates,recipe=>[base,alternate].includes(recipe.id)?4:0,60);
assert.equal(bothAvailable.find(row=>row.outputId===outputId)?.recipe.id,base,'auto prefers a craftable standard recipe');
const regional=alchemyPotionRows(candidates,recipe=>recipe.id===alternate?4:0,60);
assert.equal(regional.find(row=>row.outputId===outputId)?.recipe.id,alternate,'auto falls back to a craftable regional recipe');
assert.equal(regional.find(row=>row.outputId===outputId)?.outputId,outputId,'source changes keep stable card identity');
const manuallyStandard=alchemyPotionRows(candidates,recipe=>recipe.id===alternate?4:0,60,{manualByOutput:{[outputId]:base}});
assert.equal(manuallyStandard.find(row=>row.outputId===outputId)?.recipe.id,base,'manual ingredient source can be inspected even when unaffordable');
const readyOnly=alchemyPotionRows(candidates,recipe=>recipe.id===alternate?4:0,60,{manualByOutput:{[outputId]:base},readyOnly:true});
assert.equal(readyOnly.length,1,'craftable-only hides every potion without a viable brewing source');
assert.equal(readyOnly[0].recipe.id,alternate,'craftable-only overrides a manually selected unavailable variant');
const active=alchemyPotionRows(candidates,recipe=>recipe.id===alternate?4:0,60,{manualByOutput:{[outputId]:alternate},activeId:base});
assert.equal(active.find(row=>row.outputId===outputId)?.recipe.id,base,'running recipe remains visible even when another recipe can be brewed');
const runningOnly=alchemyPotionRows(candidates,unavailable,60,{activeId:base,readyOnly:true});
assert.equal(runningOnly.length,1,'running potion remains visible even when reserved materials make it temporarily uncraftable');
assert.equal(runningOnly[0].recipe.id,base,'craftable-only does not swap away from the running recipe');

const preferred=alchemyPotionRows(candidates,unavailable,60,{preferredId:alternate});
assert.equal(preferred.find(row=>row.outputId===outputId)?.recipe.id,alternate,'deep links preserve preferred recipe when nothing is craftable');
console.log('PASS Alchemy potion workshop: 12 unique potion cards, auto/manual source selection, active priority, craftable-only, stable card identity.');
