import {assert} from './test-assert';
import {effectiveStats,previewActivityReward,claimActivity} from '../src/core/game';
import {liveHealthState} from '../src/core/live-health';
import {executeGameCommand} from '../src/core/game-commands';
import {newInventoryScreenState,openInventoryFood} from '../src/core/inventory-screen-state';
import {REGIONAL_COMBAT_FIXTURES,regionalCombatFixture} from '../src/core/regional-combat-fixtures';
const T=Date.UTC(2026,9,1,12),H=3600000,region=REGIONAL_COMBAT_FIXTURES[0];
const state=regionalCombatFixture(region,'prepared');
state.activity={kind:'combat',targetId:region.monsterId,startedAtMs:T,lastClaimAtMs:T};
state.character!.currentHp=effectiveStats(state).hp;
state.inventory.stacks=[];
const before=JSON.stringify(state),reward=previewActivityReward(state,T+H/4),live=liveHealthState(state,T+H/4);
assert.equal(live.character!.currentHp,reward.endHp,'header HP matches pending combat damage');
assert.equal(JSON.stringify(state),before,'projection must not mutate the saved character');
assert.equal(liveHealthState(state,T+8*H).character!.currentHp,1,'header shows injury before claiming');
const pending=structuredClone(state);pending.character!.equippedFoodId=undefined;pending.inventory.stacks=[{itemId:region.foodId,quantity:3}];
const settledEat=executeGameCommand(pending,{type:'eat',args:{id:region.foodId}},T+8*H);
assert.equal(settledEat.reward?.kills,previewActivityReward(pending,T+8*H).kills,'manual eating cannot retroactively extend a defeated hunt');
assert.ok(!settledEat.state.activity&&settledEat.state.character!.currentHp>1,'pending defeat settles before manual healing');
const stocked=structuredClone(state);stocked.inventory.stacks=[{itemId:region.foodId,quantity:100}];stocked.character!.equippedFoodId=region.foodId;
const foodReward=previewActivityReward(stocked,T+H),foodView=liveHealthState(stocked,T+H);
assert.equal(foodView.inventory.stacks[0].quantity,100-(foodReward.foodConsumed??0),'quick food excludes food already consumed by combat');
const injured=claimActivity(state,T+8*H).state;
injured.inventory.stacks=[{itemId:region.foodId,quantity:3}];
const ate=executeGameCommand(injured,{type:'eat',args:{id:region.foodId}},T+8*H).state;
assert.ok(ate.character!.currentHp>1,'eating recovers an injured character');
assert.equal(ate.inventory.stacks[0].quantity,2,'one action consumes one food');
const resumed=executeGameCommand(ate,{type:'start',args:{kind:'combat',id:region.monsterId}},T+8*H).state;
assert.equal(resumed.activity?.targetId,region.monsterId,'recovered hunt can be explicitly resumed');
const rested=liveHealthState(injured,T+9*H);
assert.ok(rested.character!.currentHp>=injured.character!.currentHp,'idle recovery is reflected in the header');
const browsing={...newInventoryScreenState(),location:'bank' as const,query:'iron',filter:'gear' as const,sort:'name' as const,scrollY:420};
const food=openInventoryFood(browsing,1);
assert.equal(food.location,'inventory');assert.equal(food.filter,'food');assert.equal(food.query,'');assert.equal(food.scrollY,0);assert.equal(food.sort,'name');
assert.equal(browsing.scrollY,420,'food navigation does not mutate another saved view');
assert.equal(newInventoryScreenState().foodRequest,0,'fresh characters have independent browsing defaults');
console.log('PASS live HP, food projection, recovery/resume, immutable views and food navigation');
