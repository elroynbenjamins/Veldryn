import { strict as assert } from "node:assert";
import { validateGuildShopPurchase } from "../src/purchase-policy";
import { validateConstructionDonation } from "../src/construction-policy";
const purchase=validateGuildShopPurchase("guild_pet_01",3,2000,[]);
assert.equal(purchase.ok,true);
if(purchase.ok) assert.equal(purchase.entry.tokenCost,2000);
assert.deepEqual(validateGuildShopPurchase("guild_pet_01",2,5000,[]),{ok:false,reason:"guild_level_locked"});
assert.deepEqual(validateGuildShopPurchase("guild_pet_01",3,5000,["guild_pet_01"]),{ok:false,reason:"already_owned"});
assert.deepEqual(validateGuildShopPurchase("guild_pet_01",null,5000,[]),{ok:false,reason:"guild_membership_required"});
assert.deepEqual(validateGuildShopPurchase("nonexistent",20,99999,[]),{ok:false,reason:"unknown_item"});
const donation={templateId:"stormwatch_banner",guildLevel:5,completed:false,resourceId:"GREENWOOD_LOG",amount:100,alreadyContributed:0};
assert.equal(validateConstructionDonation(donation).ok,true);
assert.deepEqual(validateConstructionDonation({...donation,guildLevel:4}),{ok:false,reason:"guild_level_locked"});
assert.deepEqual(validateConstructionDonation({...donation,completed:true}),{ok:false,reason:"project_completed"});
assert.deepEqual(validateConstructionDonation({...donation,resourceId:"diamonds"}),{ok:false,reason:"invalid_resource"});
assert.deepEqual(validateConstructionDonation({...donation,amount:10001}),{ok:false,reason:"exceeds_remaining"});
assert.deepEqual(validateConstructionDonation({...donation,amount:0}),{ok:false,reason:"invalid_amount"});
assert.deepEqual(validateConstructionDonation({...donation,amount:101,alreadyContributed:9900}),{ok:false,reason:"exceeds_remaining"});
console.log("Guild purchase and construction policy tests passed");
