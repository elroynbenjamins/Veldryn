const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const src=path=>readFileSync('src/components/coop/'+path,'utf8');
const live=src('CoopLobbyPresentation.tsx');
const lobby=src('CoopLiveLobby.tsx');
const loadout=src('CoopLoadoutSelection.tsx');
const setup=src('CoopCombatSetupPanel.tsx');
const roster=src('CoopRunOverview.tsx');
const chip=src('CoopPartyCompanionChip.tsx');
const screen=readFileSync('src/screens/CoopExpeditionScreen.tsx','utf8');
assert.match(live,/setupState\?\.character&&!ended\?<CoopCombatSetupPanel/, 'Live queue and ready check show the current combat setup');
assert.match(lobby,/setupState=\{setupState\}/, 'queue forwards character setup');
assert.match(screen,/setupState=\{state\}/, 'current GameState is the setup source');
assert.match(loadout,/<CoopCombatSetupPanel state=\{state\}/, 'show setup before joining either mode');
assert.match(setup,/accessibilityState=\{\{expanded:expanded==='companion'\}\}/, 'companion detail toggle accessible');
assert.match(setup,/accessibilityState=\{\{expanded:expanded==='healing'\}\}/, 'healing detail toggle accessible');
assert.match(setup,/No potion is spent while queueing/, 'no automatic expenditure promises');
assert.match(roster,/slot\.companionId\?<CoopPartyCompanionChip/, 'Echo assist exists only on actual snapshot');
assert.match(roster,/companionSlot\.echo\?st\('Frozen Echo companion'\)/, 'frozen Echo origin labeled');
assert.match(chip,/if\(!companion\)return null/, 'no invented companion for NPCs');
assert.match(chip,/accessibilityState=\{\{expanded\}\}/, 'Echo companion details keyboard and screen reader accessible');
assert.doesNotMatch(live,/ownerAccountId|sourceAccountId|inventory\.stacks/, 'Live roster must not show other inventories');
assert.match(chip,/Frozen Echo companion/, 'frozen Echo assist must be identified in the roster');
assert.match(setup,/tonicPreviewId/, 'tonic summary uses existing potion artwork');
assert.match(roster,/companionMemberId/, 'companion detail state exists and can be dismissed');
console.log('PASS compact Live, loadout and frozen Echo companion UI wiring');
