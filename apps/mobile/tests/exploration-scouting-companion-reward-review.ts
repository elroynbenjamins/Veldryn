import assert from 'node:assert/strict';
import {freezeScoutCompanionReward,settleScoutRareReward,applyScoutCompanionProgress,claimLegacyScoutingReport,SCOUT_COMPANION_REWARD_RELEASED} from '../src/core/exploration-scouting-companion-reward-review';
import {claimCompanionAssignment} from '../../../backend/src/server/companions/assignments';
import {companionMission} from '../../../backend/src/server/companions/content';
import {companionTrialWeekKey} from '../../../backend/src/server/companions/trial-season';
import {newGame,createCharacter} from '../src/core/game';
import type {CompanionAssignment,OwnedCompanionSnapshot} from '../../../backend/src/server/companions/domain';
const now=Date.UTC(2026,10,24),end=now+7200000,seed='review-only-private-test-seed-123456789';
const owned:Record<string,OwnedCompanionSnapshot>={UNIT_001:{companionId:'UNIT_001',level:10,xp:0,ascensionTier:0,bondLevel:1,bondXp:0,bondTraitUnlocked:false}};
const mission=companionMission('MISSION_SCOUT_2H')!;
const assignment:CompanionAssignment={assignmentId:'legacy1',missionId:mission.id,missionVersion:mission.missionVersion,companionIds:['UNIT_001'],startedAt:new Date(now).toISOString(),endsAt:new Date(end).toISOString(),seed,status:'active'};
const expected=claimCompanionAssignment({assignment,owned,serverNowMs:end,bondstonesClaimedThisWeek:0});
const frozen=freezeScoutCompanionReward({missionId:mission.id,assignmentId:'legacy1',companionIds:['UNIT_001'],owned,startedAt:now,endsAt:end,serverSeed:seed});
assert.equal(SCOUT_COMPANION_REWARD_RELEASED,false);
assert.deepEqual(frozen.reward,expected.reward);assert.equal(frozen.grade,expected.assignment.performanceGrade);
assert.throws(()=>freezeScoutCompanionReward({missionId:mission.id,assignmentId:'x',companionIds:['UNIT_001'],owned,startedAt:now,endsAt:end,serverSeed:'short'}),/invalid_reward_reservation/);
const eligible={...frozen,reward:{...frozen.reward,bondstones:1}};
const first=settleScoutRareReward(eligible,undefined,end);
assert.equal(first.reward.bondstones,1);
assert.equal(settleScoutRareReward(eligible,first.weekly,end).reward.bondstones,0);
assert.equal(settleScoutRareReward(eligible,first.weekly,end+7*86400000).reward.bondstones,1);
assert.equal(settleScoutRareReward(eligible,{week:companionTrialWeekKey(end),used:1},end).reward.bondstones,0);
const progressed=applyScoutCompanionProgress({owned,reward:frozen.reward,companionIds:['UNIT_001'],essence:5,now:end});
assert.ok(progressed.essence>=5+frozen.reward.companionEssence);
assert.ok(progressed.owned.UNIT_001.level>=owned.UNIT_001.level);
assert.equal(owned.UNIT_001.xp,0);
const game=createCharacter(newGame(now),'IRONWARDEN','Legacy');
const fixture={...game,account:{...game.account,companionAssignments:[assignment]}};
assert.throws(()=>claimLegacyScoutingReport(fixture,'legacy1',end-1),/legacy_assignment_not_ready/);
assert.throws(()=>claimLegacyScoutingReport(fixture,'missing',end),/legacy_assignment_missing/);
const already={...fixture,account:{...fixture.account,companionAssignments:[expected.assignment]}};
assert.equal(claimLegacyScoutingReport(already,'legacy1',end+1000),already);
console.log('PASS canonical mission reward parity, weekly rare cap, progression adapter, legacy claim guards');
