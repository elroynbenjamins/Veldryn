import assert from 'node:assert/strict';
import {newGame,createCharacter} from '../src/core/game';
import {WORLD_ZONES} from '../src/content/world-map';
import {MONSTERS} from '../src/content/monsters';
import {regionTravelAvailability} from '../src/core/world-navigation';
import {SCOUT_ROUTES,scoutingAvailability,scoutClaimPreview,reserveScout,type ScoutState,type ScoutAuthority} from '../src/core/exploration-scouting-review';
import {captureLegacyScoutingAccess,captureLegacyScoutingRoster,retainLegacyScoutingProgress,retainedRegionAccess,retainedAreaAccess,retainedRegularEncounterAccess,SCOUT_CUTOVER_RELEASED} from '../src/core/exploration-scouting-cutover-review';
import type {GameState} from '../src/core/types';
const first=createCharacter(newGame(1000),'IRONWARDEN','Veteran');
const second=createCharacter(newGame(2000),'IRONWARDEN','Newcomer');
const zone=(id:string)=>WORLD_ZONES.find(z=>z.id===id)!;
const veteran:GameState={...first,character:{...first.character!,id:'veteran',level:64},skills:first.skills.map(s=>s.skillId==='exploration'?{...s,xp:1200,level:4}:s),currentRegionId:'FROSTMARCH',exploredRouteIds:['SCOUT_KINGS_ROAD','SCOUT_SUNSCAR'],defeatedBossIds:['FALLEN_KNIGHT']};
const newbie:GameState={...second,character:{...second.character!,id:'newbie',level:1},currentRegionId:'GREENFIELDS',exploredRouteIds:[],defeatedBossIds:[],unlockedMonsterIds:['MOSS_RAT']};
const accountId='account',now=12345;
const snapshot=captureLegacyScoutingAccess(accountId,veteran,now);
assert.equal(SCOUT_CUTOVER_RELEASED,false);
for(const z of WORLD_ZONES){assert.equal(snapshot.regionIds.includes(z.id),regionTravelAvailability(veteran,z)==='available');}
assert.ok(snapshot.regionIds.includes('SUNSCAR')&&snapshot.regionIds.includes('FROSTMARCH'));
assert.ok(snapshot.areaIds.includes('ZONE_011')&&snapshot.areaIds.includes('ZONE_012')&&snapshot.areaIds.includes('ZONE_013'));
assert.ok(!snapshot.areaIds.includes('ZONE_015'));
const low:ScoutState={accountId,characterId:'veteran',explorationLevel:1,explorationXp:0,discoveredRouteIds:[],visitedZoneIds:[]};
const retained=retainLegacyScoutingProgress(low,snapshot);
assert.equal(retained.explorationXp,1200);assert.equal(retained.explorationLevel,4);
assert.deepEqual(retained.discoveredRouteIds,['SCOUT_KINGS_ROAD','SCOUT_SUNSCAR']);
assert.ok(retained.retainedPrerequisiteRouteIds?.includes('SCOUT_IRONWOOD'));
assert.ok(retainedRegionAccess(retained,zone('FROSTMARCH'),snapshot,false));
assert.ok(retainedAreaAccess(retained,'FROSTMARCH','ZONE_013',snapshot,false));
assert.ok(!retainedAreaAccess(retained,'FROSTMARCH','ZONE_015',snapshot,false));
assert.ok(!retainedRegionAccess(retained,zone('ASHLANDS'),snapshot,true));
assert.ok(!retainedRegionAccess(retained,zone('VEILLANDS'),snapshot,true));
assert.deepEqual(retainLegacyScoutingProgress(retained,snapshot),retained);
const higher={...retained,explorationXp:9999,explorationLevel:20,discoveredRouteIds:[...retained.discoveredRouteIds,'SCOUT_FROSTMARCH']};
const updated=retainLegacyScoutingProgress(higher,snapshot);assert.equal(updated.explorationXp,9999);assert.ok(updated.discoveredRouteIds.includes('SCOUT_FROSTMARCH'));
const other={...low,characterId:'newbie'};
assert.equal(retainLegacyScoutingProgress(other,snapshot),other);
assert.ok(!retainedRegionAccess(other,zone('FROSTMARCH'),snapshot,false));
assert.ok(!retainedRegionAccess({...retained,accountId:'another'},zone('FROSTMARCH'),snapshot,false));
const roster=captureLegacyScoutingRoster(accountId,{...veteran,otherCharacters:[{character:newbie.character!,inventory:newbie.inventory,overflow:newbie.overflow,activity:newbie.activity,skills:newbie.skills,quests:newbie.quests,currentRegionId:newbie.currentRegionId,unlockedMonsterIds:newbie.unlockedMonsterIds,exploredRouteIds:newbie.exploredRouteIds,defeatedBossIds:newbie.defeatedBossIds}]},now);
assert.equal(roster.length,2);assert.ok(!roster[1].regionIds.includes('FROSTMARCH'));assert.equal(roster[1].explorationXp,0);
const historical={...veteran,character:{...veteran.character!,level:12},currentRegionId:'ASHLANDS',exploredRouteIds:[],defeatedBossIds:[]};
const old=captureLegacyScoutingAccess(accountId,historical,now);
assert.ok(old.regionIds.includes('FROSTMARCH'));assert.ok(!old.regionIds.includes('ASHLANDS'));
const flagsOnly=captureLegacyScoutingAccess(accountId,{...newbie,unlockedMonsterIds:['FROSTWOLF']},now);
assert.ok(!flagsOnly.regionIds.includes('FROSTMARCH'));
assert.ok(!retainedRegularEncounterAccess(retained,'FALLEN_KNIGHT',snapshot,false));
for(const id of snapshot.regularEncounterIds){assert.ok(retainedRegularEncounterAccess(retained,id,snapshot,false));assert.ok(!MONSTERS.find(m=>m.id===id)?.boss);}
const frontier=SCOUT_ROUTES.find(r=>r.legacyId==='SCOUT_FROSTMARCH')!;
assert.equal(scoutingAvailability({...retained,explorationLevel:12},frontier,'route'),'available');
const authority:ScoutAuthority={owned:{},legacyAssignments:[],equipped:new Set(),trialLocked:new Set(),unavailable:new Set()};
const state={...retained,explorationLevel:12};
const r=reserveScout({state,authority,receipts:[],routeId:frontier.id,kind:'route',companionIds:[],requestId:'frontier_01',now});
assert.equal(scoutClaimPreview(r,state,r.endsAt).newDiscovery,'SCOUT_FROSTMARCH');
assert.equal(scoutClaimPreview(r,state,r.endsAt).travelUnlocked,false);
console.log('PASS legacy scouting cutover: travel and areas, independent characters, historical access, idempotent XP/route preservation, unreleased and boss guards');

import {scoutingGuide} from '../src/core/exploration-scouting-tutorial-review';
const oldGuide=scoutingGuide({state:retained,receipts:[],now,ownedCompanionCount:0,returningPlayer:true,acknowledged:['scouting2_returning']});
assert.equal(oldGuide?.id,'scouting2_practice');
assert.ok(oldGuide?.routeId);
const guideRoute=SCOUT_ROUTES.find(x=>x.id===oldGuide?.routeId)!;
assert.equal(scoutingAvailability(retained,guideRoute,'practice'),'available');
const veteranNext=scoutingGuide({state:{...retained,explorationLevel:12},receipts:[],now,ownedCompanionCount:0,returningPlayer:true,acknowledged:['scouting2_returning']});
assert.ok(veteranNext?.routeId&&!retained.retainedPrerequisiteRouteIds?.includes(veteranNext.routeId.replace('scout2:','')));
