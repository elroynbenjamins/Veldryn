const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const entry=read('backend/online/coop-entry.ts');
const server=read('backend/online/live-runtime.ts');
const domain=read('backend/src/server/coop/qmode.ts');
const resolver=read('backend/src/server/expeditions/node-resolution.ts');
const details=read('apps/mobile/src/components/coop/CoopDungeonBrowser.tsx');
const screen=read('apps/mobile/src/screens/CoopExpeditionScreen.tsx');
const browse=read('apps/mobile/src/core/coop-dungeon-browsing.ts');
const migration=read('backend/supabase/migrations/20261104000011_coop_reward_budget_read_v1.sql');
assert(entry.includes('expectedMarksByTier:Object.fromEntries')&&entry.includes('baseMarks(def.baseMarks,tier)'),'Estimates must be calculated on the backend from canonical per-tier rewards');
assert(entry.includes('online_coop_reward_budget_server_v1'),'Weekly reward counts come from read-only server state');
assert(migration.includes('revoke all on function')&&migration.includes('to service_role'),'Budget read must not expose direct public RPC access');
assert(domain.includes('tierScalingVersion:2')&&resolver.includes('coopTierEnemyMultipliers(input.tier)'),'Only new versioned runs receive tier-based enemy scaling');
assert(server.includes('enhancedDungeonMarks(run)'),'Live rewards must share tier and failure formulas, not flat percentage');
assert(details.includes('dungeon.expectedMarksByTier?.[effectiveTier]')&&details.includes('rewardBudget.weeklyRemaining'),'Preparation must show selected-tier Marks and weekly remaining');
assert(screen.includes('rewardBudget={entry?.rewardBudget}'),'Screen must receive server-owned reward budget');
assert(browse.includes('estimatedMinutes??{min:3,max:5}'),'Dungeon timing must reflect the newer 3–5 minute target');
console.log('PASS dungeon reward previews, weekly charge safety, versioned difficulty and Live parity UI');
