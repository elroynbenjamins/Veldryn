import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {auditStoryPacing} from './story-journal-2-pacing-review.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const books=['asterfall','sunscar','frostmarch'].map(n=>JSON.parse(read('docs/2-0/story-'+n+'-review-v1.json')));
const routes={SCOUT_SILVERBROOK:'SCOUT_GREENFIELDS',SCOUT_IRONWOOD:'SCOUT_SILVERBROOK',SCOUT_OLD_MINES:'SCOUT_IRONWOOD',SCOUT_KINGS_ROAD:'SCOUT_OLD_MINES',SCOUT_SUNSCAR:'SCOUT_KINGS_ROAD',SCOUT_SUNSCAR_SCORCHWIND:'SCOUT_SUNSCAR',SCOUT_SUNSCAR_MIRAGE:'SCOUT_SUNSCAR_SCORCHWIND',SCOUT_SUNSCAR_CROWN:'SCOUT_SUNSCAR_MIRAGE',SCOUT_FROSTMARCH:'SCOUT_SUNSCAR',SCOUT2_FROST_WHITEPINE:'SCOUT_FROSTMARCH',SCOUT2_FROST_SHIVERLAKE:'SCOUT2_FROST_WHITEPINE',SCOUT2_FROST_WYRMSPINE:'SCOUT2_FROST_SHIVERLAKE'};
const audit=auditStoryPacing(books,routes);
assert.deepEqual(audit.issues,[]);
assert.equal(audit.routeCount,13);
assert.equal(audit.authorizesAccess,false);
const broken=structuredClone(books);
broken[0].quests.find(q=>q.legacyQuestId==='QST_007').objectives.shift();
assert.ok(auditStoryPacing(broken,routes).issues.some(i=>i.reason==='missing_earlier_route'));
const companion=books[0].quests.find(q=>q.legacyQuestId==='QST_005');
assert.ok(companion.objectives.some(o=>o.kind==='level'&&o.required===10));
const ui=read('apps/mobile/src/components/StoryJournalRecords2Review.tsx');
assert.ok(ui.includes('StoryChallengePanel2Review')&&ui.includes('StoryRecordsPanel2Review'));
assert.ok(!ui.includes('onClaim'));
console.log('Story pacing and read-only challenge/record panels: PASS');
