import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {regionalRewardReview} from './story-journal-2-rewards-review.mjs';
import {rehearseQuestClaim} from './story-journal-2-claim-review.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const names=['asterfall','sunscar','frostmarch'];
const books=names.map(n=>JSON.parse(read('docs/2-0/story-'+n+'-review-v1.json')));
const sides=names.map(n=>JSON.parse(read('docs/2-0/story-'+n+'-side-review-v1.json')));
const legacy=[...read('apps/mobile/src/content/quests.ts').matchAll(/\{id:'(QST_\d+)'[^\n]*?rewardGold:(\d+)/g)].map(m=>({id:m[1],gold:+m[2]}));
const regions={'Greenfields':'ASTERFALL','Silverbrook':'ASTERFALL','Ironwood Forest':'ASTERFALL','Old Mines':'ASTERFALL',"King's Road":'ASTERFALL','Sunscar':'SUNSCAR','Frostmarch':'FROSTMARCH'};
const enemies=[...read('apps/mobile/src/content/monsters.ts').matchAll(/\{id:'([^']+)',name:'[^']+',level:\d+,hp:\d+,attack:\d+,defense:\d+,xp:\d+,gold:(\d+),secondsPerKill:(\d+),[^\n]*?zone:('[^']+'|"[^"]+")([^\n]*)/g)].map(m=>({id:m[1],gold:+m[2],seconds:+m[3],regionId:regions[m[4].slice(1,-1)],boss:m[5].includes('boss:true')})).filter(e=>e.regionId);
const budgets=regionalRewardReview(books,sides,enemies,legacy);
assert.equal(budgets.status,'review');
assert.equal(budgets.regions[0].mainBudget,6100);
for(const r of budgets.regions){
 assert.equal(r.main.reduce((n,x)=>n+x.candidateGold,0),r.mainBudget);
 assert.equal(r.side.reduce((n,x)=>n+x.candidateGold,0),r.sideBudget);
 assert.ok(r.main.every(x=>!x.authorizesReward));
}
assert.ok(budgets.regions[1].mainBudget<=12200);
assert.ok(budgets.regions[2].mainBudget<=18300);
assert.equal(budgets.regions[2].main.at(-1).pendingBinding,true);
console.log('Candidate regional budgets:',budgets.regions.map(r=>[r.regionId,r.mainBudget,r.sideBudget]));
const expected={accountId:'a',characterId:'c'},book=books[0],side=sides[0],questId=book.quests[0].id;
const snapshot={...expected,revision:7,sequence:2,level:1,equippedCount:1,actualAccountMaps:[],retainedCharacterRoutes:[],soloBossVictories:[],claimedLegacyIds:[],claimedStoryIds:[],activationSequences:{[questId]:0},events:[{...expected,receiptId:'event',sequence:1,kind:'kill',targetId:'MOSS_RAT',quantity:5,status:'settled'}]};
const ledger={...expected,revision:7,gold:100,receipts:[],claimedQuestIds:[],migrationLane:'fresh_v2_candidate'};
const request={requestId:'req1',questId,expectedRevision:7,policyVersion:'fixture-v1'};
const policy={mode:'synthetic_review',released:false,version:'fixture-v1',rewards:[{questId,gold:40}]};
const args={book,side,snapshot,expected,ledger,request,policy};
const result=rehearseQuestClaim(args);
assert.equal(result.status,'proposed');assert.equal(result.proposedLedger.gold,140);assert.equal(result.persisted,false);assert.equal(ledger.gold,100);
assert.equal(rehearseQuestClaim({...args,ledger:result.proposedLedger}).status,'replay');
assert.equal(rehearseQuestClaim({...args,ledger:result.proposedLedger,request:{...request,questId:'other'}}).reason,'request_conflict');
assert.equal(rehearseQuestClaim({...args,ledger:result.proposedLedger,request:{...request,requestId:'req2'}}).reason,'stale_revision');
assert.equal(rehearseQuestClaim({...args,ledger:result.proposedLedger,snapshot:{...snapshot,revision:8,claimedStoryIds:[questId]},request:{...request,requestId:'req2',expectedRevision:8}}).reason,'already_claimed');
assert.equal(rehearseQuestClaim({...args,ledger:{...ledger,migrationLane:'legacy_continuation'}}).reason,'legacy_lane');
assert.equal(rehearseQuestClaim({...args,snapshot:{...snapshot,events:[]}}).reason,'quest_not_ready');
assert.equal(rehearseQuestClaim({...args,snapshot:{...snapshot,claimedStoryIds:[questId]}}).reason,'claim_state_mismatch');
assert.equal(rehearseQuestClaim({...args,expected:{...expected,characterId:'other'}}).reason,'foreign_scope');
assert.equal(rehearseQuestClaim({...args,policy:{...policy,released:true}}).reason,'invalid_contract');
console.log('Regional reward envelope and non-authorizing claim rehearsal: PASS');
