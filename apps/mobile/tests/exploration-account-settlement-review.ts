import assert from 'node:assert/strict';
import {newGame,createCharacter} from '../src/core/game';
import {totalXpAtLevel,levelFromXp} from '../src/core/progression';
import {accountSkillLevel,unlockedCharacterSlots} from '../src/core/account-roster';
import {captureLegacyScoutingRoster} from '../src/core/exploration-scouting-cutover-review';
import {migrateAccountExploration,projectAccountExploration,characterSlotSkillTotal2Review,unlockedCharacterSlots2Review,ACCOUNT_EXPLORATION_RELEASED} from '../src/core/exploration-account-review';
import {dispatchTrainingReview,dispatchCampReview,claimScoutingReview,type ScoutLedger} from '../src/core/exploration-scouting-settlement-review';
import type {GameState} from '../src/core/types';
import type {ScoutState} from '../src/core/exploration-scouting-review';
const base=createCharacter(newGame(1000),'IRONWARDEN','First'),alt=createCharacter(newGame(2000),'IRONWARDEN','Second');
const skills=base.skills.map(s=>s.skillId==='exploration'?{...s,level:20,xp:totalXpAtLevel(20)}:s);
const otherSkills=alt.skills.map(s=>s.skillId==='exploration'?{...s,level:10,xp:totalXpAtLevel(10)}:s);
const state:GameState={...base,character:{...base.character!,id:'c1'},skills,exploredRouteIds:['SCOUT_GREENFIELDS'],otherCharacters:[{character:{...alt.character!,id:'c2'},inventory:alt.inventory,overflow:alt.overflow,activity:null,skills:otherSkills,quests:alt.quests,currentRegionId:'GREENFIELDS',unlockedMonsterIds:['MOSS_RAT'],exploredRouteIds:[],defeatedBossIds:[]}],account:{...base.account,unlockedCharacterSlots:2}};
const legacy=captureLegacyScoutingRoster('a',state,1000),account=migrateAccountExploration('a',legacy,state);
assert.equal(ACCOUNT_EXPLORATION_RELEASED,false);
assert.equal(account.xp,totalXpAtLevel(20)+totalXpAtLevel(10));assert.equal(account.level,levelFromXp(account.xp));
assert.equal(characterSlotSkillTotal2Review(state),accountSkillLevel(state)-30);
assert.equal(unlockedCharacterSlots2Review(state,account),unlockedCharacterSlots(state));
assert.equal(migrateAccountExploration('a',legacy,state,account),account);
assert.throws(()=>migrateAccountExploration('a',[legacy[0],legacy[0]],state),/invalid_legacy_snapshot/);
assert.throws(()=>migrateAccountExploration('a',[legacy[0]],state),/incomplete_roster_snapshot/);
const first:ScoutState={accountId:'a',characterId:'c1',explorationXp:0,explorationLevel:1,discoveredRouteIds:['SCOUT_GREENFIELDS'],visitedZoneIds:['GREENFIELDS']};
const second={...first,characterId:'c2',discoveredRouteIds:[]};
assert.equal(projectAccountExploration(second,account).explorationLevel,account.level);
assert.deepEqual(projectAccountExploration(second,account).discoveredRouteIds,[]);
let l:ScoutLedger={account,characters:{c1:first,c2:second},wallets:{c1:{gold:1000,materials:{TRAVEL_RATION:100}},c2:{gold:0,materials:{}}},authority:{owned:{UNIT_001:{companionId:'UNIT_001',level:10,xp:0,ascensionTier:0,bondLevel:1,bondXp:0,bondTraitUnlocked:false}},legacyAssignments:[],equipped:new Set(),trialLocked:new Set(),unavailable:new Set()},pensLevel:2,training:[],camps:[],claims:[],essence:0,companionXp:{},bondXp:{}};
const cmd={requestId:'route_001',routeId:'scout2:SCOUT_GREENFIELDS',kind:'route' as const,companionIds:[]};
const started=dispatchTrainingReview(l,'a','c2',cmd,1000);l=started.ledger;
assert.equal(dispatchTrainingReview(l,'a','c2',cmd,1001).ledger,l);
assert.throws(()=>dispatchTrainingReview(l,'a','c1',{...cmd,requestId:'route_002'},1001),/scout_slot_busy/);
assert.throws(()=>claimScoutingReview(l,'a','c1',cmd.requestId,started.receipt.endsAt),/owner_mismatch/);
assert.throws(()=>claimScoutingReview(l,'a','c2',cmd.requestId,1001),/not_ready/);
const mapped=claimScoutingReview(l,'a','c2',cmd.requestId,started.receipt.endsAt);l=mapped.ledger;
assert.equal(mapped.claim.xp,0);assert.ok(l.characters.c2.discoveredRouteIds.includes('SCOUT_GREENFIELDS'));
const seed=()=> 'private-review-fixture-seed-000000000001';
const mission={requestId:'camp_001',missionId:'MISSION_SCOUT_2H',companionIds:['UNIT_001'],earnExplorationXp:true,food:[{itemId:'TRAVEL_RATION',quantity:34}]};
assert.throws(()=>dispatchCampReview(l,'a','c1',{...mission,food:[]},100000,seed),/missing_stamina/);
assert.equal(l.wallets.c1.gold,1000);
const camp=dispatchCampReview(l,'a','c1',mission,100000,seed);l=camp.ledger;
assert.equal(l.wallets.c1.gold,700);assert.equal(l.wallets.c1.materials.TRAVEL_RATION,66);
assert.equal(dispatchCampReview(l,'a','c1',mission,100001,()=>{throw Error('retry must not reroll');}).ledger,l);
assert.throws(()=>dispatchCampReview(l,'a','c1',{...mission,food:[{itemId:'TRAVEL_RATION',quantity:35}]},100001,seed),/nonce_conflict/);
assert.equal('frozen' in camp.receipt,false);
const reservedReward=structuredClone(l.camps[0].frozen.reward);
const reservedGrade=l.camps[0].frozen.grade;
const beforeClaim=l;
const paid=claimScoutingReview(l,'a','c1',mission.requestId,camp.receipt.endsAt);l=paid.ledger;
assert.equal(l.wallets.c1.gold,700+reservedReward.gold);
assert.ok(l.essence>=reservedReward.companionEssence);
assert.equal(l.companionXp.UNIT_001,reservedReward.companionXpById?.UNIT_001);
assert.equal(paid.claim.grade,reservedGrade);
assert.deepEqual(paid.claim.companionReward,reservedReward);
assert.ok((l.companionMasteryXp??0)>0);
assert.ok(Object.values(l.companionUnlockProgress??{}).some(x=>x===1));
assert.equal(beforeClaim.companionXp.UNIT_001,undefined);
assert.ok(l.authority.owned.UNIT_001.xp>0||l.authority.owned.UNIT_001.level>10);
assert.equal(l.account.xp,account.xp+1800);
assert.equal(claimScoutingReview(l,'a','c1',mission.requestId,camp.receipt.endsAt+1).ledger,l);
assert.equal(projectAccountExploration(l.characters.c2,l.account).explorationXp,l.account.xp);
console.log('PASS shared account XP migration, excluded slots, isolated routes, atomic reference dispatch and idempotent settlement');
