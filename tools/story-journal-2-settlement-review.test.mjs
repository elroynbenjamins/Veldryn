import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {rewardPacingReview,legacyStoryMigrationReview,pinnedQuestTrackerReview} from './story-journal-2-settlement-review.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const book=JSON.parse(read('docs/2-0/story-asterfall-review-v1.json'));
const old=[...read('apps/mobile/src/content/quests.ts').matchAll(/\{id:'(QST_\d+)'[^\n]*?rewardGold:(\d+)/g)].map(m=>({id:m[1],gold:+m[2]}));
const rewards=rewardPacingReview(book,old);
assert.equal(rewards.legacyBudget,6100);
assert.equal(rewards.candidateBudget,6100);
assert.ok(rewards.rows.every((r,i)=>!i||r.candidateGold>=rewards.rows[i-1].candidateGold));
assert.equal(rewards.rows.at(-1).titleId,'oathbreaker');
assert.equal(rewards.authorizesReward,false);
assert.equal(rewardPacingReview(book,[...old.slice(0,-1),{id:'fake',gold:1250}]).status,'unavailable');
const e={accountId:'a',characterId:'c'};
const s={...e,legacyStateComplete:true,legacyJourneyStarted:false,legacyQuests:old.map((r,i)=>({id:r.id,status:i===0?'active':'locked',progress:0}))};
let m=legacyStoryMigrationReview(book,s,e);
assert.equal(m.lane,'fresh_v2_candidate');
s.legacyQuests[0].progress=3;
m=legacyStoryMigrationReview(book,s,e);
assert.equal(m.lane,'legacy_continuation');
assert.equal(m.preservedRows.find(q=>q.id==='QST_001').progress,3);
s.legacyQuests[0].status='complete';
assert.deepEqual(legacyStoryMigrationReview(book,s,e).legacyClaimIds,['QST_001']);
s.legacyQuests[0].status='claimed';
assert.equal(legacyStoryMigrationReview(book,s,e).blocksV2AsterfallClaims,true);
for(const q of s.legacyQuests)q.status='claimed';
m=legacyStoryMigrationReview(book,s,e);
assert.equal(m.lane,'legacy_completed');assert.equal(m.mappedClaimedStoryIds.length,15);assert.equal(m.authorizesReward,false);
assert.equal(legacyStoryMigrationReview(book,{...s,legacyQuests:s.legacyQuests.slice(1)},e).status,'unavailable');
assert.equal(legacyStoryMigrationReview(book,{...s,legacyJourneyStarted:undefined},e).status,'unavailable');
assert.equal(legacyStoryMigrationReview(book,s,{...e,characterId:'other'}).status,'unavailable');
const context={...e,screen:'World'},model={...e,status:'review',pinned:{id:'quest1',title:'First Hunt',tab:'story',status:'active',objectives:[{id:'a',complete:true},{id:'b',complete:false,progress:3,required:5}]}};
let track=pinnedQuestTrackerReview(model,context,e);
assert.equal(track.status,'visible');assert.equal(track.objective.progress,3);assert.equal(track.destination.questId,'quest1');
for(const patch of [{inDungeon:true},{inBossFight:true},{modalOpen:true},{tutorialVisible:true},{activityControlsObscured:true},{screen:'Account'}])assert.equal(pinnedQuestTrackerReview(model,{...context,...patch},e).status,'hidden');
assert.equal(pinnedQuestTrackerReview({...model,characterId:'other'},context,e).status,'hidden');
model.pinned.status='ready';assert.equal(pinnedQuestTrackerReview(model,context,e).label,'Reward ready');
model.pinned.status='claimed';assert.equal(pinnedQuestTrackerReview(model,context,e).status,'hidden');
console.log('Reward envelope, legacy journey continuity and scoped pinned tracker: PASS');
