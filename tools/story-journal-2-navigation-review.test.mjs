import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {projectStoryReview,projectSideReview} from './story-journal-2-evidence-review.mjs';
import {journalNavigationReview,journalReturnReview} from './story-journal-2-navigation-review.mjs';
const read=p=>JSON.parse(readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const book=read('docs/2-0/story-asterfall-review-v1.json'),side=read('docs/2-0/story-asterfall-side-review-v1.json');
const accountId='account',characterId='hero',expected={accountId,characterId};
const scout=book.quests.find(q=>q.legacyQuestId==='QST_003'),fish=side.quests.find(q=>q.id==='side2:asterfall:silverbrook');
const snap={...expected,sequence:20,level:7,equippedCount:2,actualAccountMaps:[],retainedCharacterRoutes:[],soloBossVictories:[],claimedLegacyIds:['QST_001','QST_002','QST_007'],claimedStoryIds:[],activationSequences:{[scout.id]:10,[fish.id]:10},events:[]};
const catalog={world:book.zones.map(z=>({zoneId:z.zoneId,regionId:'ASTERFALL',released:true})),routes:[{id:'SCOUT_IRONWOOD',zoneId:'IRONWOOD',released:true}],enemies:[],gathering:[{id:'fish1',skillId:'fishing',itemId:'SILVERFIN',zoneId:'SILVERBROOK',released:true},{id:'fish2',skillId:'fishing',itemId:'SILVERFIN',zoneId:'GREENFIELDS',released:true}]};
const context={...expected,currentZoneId:'SILVERBROOK',access:{fish1:{status:'allowed'},fish2:{status:'allowed'}},scouting:{...expected,assignments:[],routeEligibility:{SCOUT_IRONWOOD:{status:'available'}}}};
const project=(preferences={},override={})=>journalNavigationReview({book,side,storyProgress:projectStoryReview(book,snap,expected),sideProgress:projectSideReview(side,snap,expected),catalog,context,preferences,...override});
const view=(preferences={},override={})=>project(preferences,{storyProgress:projectStoryReview(book,snap,expected),...override});
let result=view();
assert.equal(result.featured.id,scout.id);
assert.equal(result.featured.primary.label,'Choose scout');
assert.equal(result.featured.primary.destination.section,'Routes');
assert.equal(result.featured.primary.destination.returnTo.questId,scout.id);
assert.equal(result.storyComplete,3);
assert.equal(result.authorizesReward,false);
const assignment={...expected,id:'assignment',routeId:'SCOUT_IRONWOOD',kind:'discovery',status:'running',usesTrainingSlot:true};
context.scouting.assignments=[assignment];
assert.equal(view().featured.primary.label,'View scouting');
assignment.status='ready';
assert.equal(view().featured.primary.label,'View report');
assert.equal(view().featured.primary.destination.assignmentId,'assignment');
assignment.characterId='other';
assert.match(view().featured.primary.detail,/Another character/);
assert.equal(view().featured.primary.destination.assignmentId,undefined);
context.scouting.assignments=[];
context.scouting.routeEligibility.SCOUT_IRONWOOD={status:'blocked',reason:'Exploration level 3 required'};
assert.equal(view().featured.primary.detail,'Exploration level 3 required');
context.scouting.routeEligibility.SCOUT_IRONWOOD={status:'available'};
const prefs={...expected,tab:'quests',filter:'current',pinnedQuestId:fish.id,query:'ferryman'};
result=view(prefs);
assert.equal(result.visible.length,1);
assert.equal(result.pinned.primary.destination.gatheringId,'fish1');
context.currentZoneId='IRONWOOD';
assert.equal(view(prefs).pinned.primary.choices.length,2);
context.access.fish1={status:'blocked',reason:'Fishing level required'};
assert.equal(view(prefs).pinned.primary.destination.gatheringId,'fish2');
context.access.fish2={status:'blocked',reason:'Travel required'};
assert.equal(view(prefs).pinned.primary.label,'View requirements');
assert.equal(view({...prefs,characterId:'other'}).tab,'story');
const back=view().featured.primary.destination.returnTo;
assert.equal(journalReturnReview(back,expected,[scout.id]).questId,scout.id);
assert.equal(journalReturnReview(back,{...expected,accountId:'other'},[scout.id]).questId,undefined);
assert.equal(journalReturnReview(back,expected,[]).tab,'story');
snap.actualAccountMaps=['SCOUT_IRONWOOD'];
snap.characterDiscoveredRoutes=['SCOUT_IRONWOOD'];
assert.equal(view().featured.primary.label,'Review rewards');
assert.equal(view().featured.primary.authorizesReward,false);
assert.equal(view().featured.primary.destination,null);
assert.equal(view({}, {storyProgress:{status:'unavailable'}}).status,'unavailable');
console.log('Story Journal navigation, scouting states, source selection, scoped preferences and return links: PASS');
