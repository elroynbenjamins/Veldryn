/**
 * Fail CI when the deployed gameplay Edge entrypoint is stale relative to the
 * shared mobile/backend engine. Regeneration is intentionally read-only here.
 */
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'backend/package.json'));
// Keep source labels deterministic regardless of where this tool was invoked.
const backendRoot=path.join(root,'backend');
const {build}=require('esbuild');
const output=path.join(root,'backend/supabase/functions/gameplay/index.ts');
const built=await build({
 absWorkingDir:backendRoot,
 entryPoints:[path.join(root,'backend/online/edge.ts')],
 outfile:output,
 bundle:true,format:'esm',platform:'neutral',
 external:['node:crypto'],target:'es2022',legalComments:'none',
 banner:{js:'// GENERATED by tools/build-online.mjs from the shared, tested game engine. Do not edit.'},
 logLevel:'silent',write:false,
});
if(built.outputFiles.length!==1)throw Error('Unexpected gameplay bundle output count');
const checkedIn=readFileSync(output,'utf8'),rebuilt=built.outputFiles[0].text;
if(checkedIn!==rebuilt){

 let offset=0;while(offset<Math.min(checkedIn.length,rebuilt.length)&&checkedIn[offset]===rebuilt[offset])offset++;
 console.error('Bundle difference:',{onDiskLength:checkedIn.length,rebuiltLength:rebuilt.length,offset});
 console.error('Disk around difference:',JSON.stringify(checkedIn.slice(Math.max(0,offset-90),offset+170)));
 console.error('Expected around difference:',JSON.stringify(rebuilt.slice(Math.max(0,offset-90),offset+170)));
 console.error('FAIL: generated gameplay Edge bundle is out of sync with the shared game engine.');
 console.error('Run pnpm --dir backend build:online, review gameplay/index.ts, and commit the generated artifact.');
 process.exitCode=1;
}else console.log('PASS: committed gameplay Edge bundle exactly matches canonical shared game engine.');

const coopOutput=path.join(root,'backend/supabase/functions/coop/index.ts');
const coopBuilt=await build({
 absWorkingDir:backendRoot,
 entryPoints:[path.join(root,'backend/online/coop-edge.ts')],
 outfile:coopOutput,
 bundle:true,format:'esm',platform:'neutral',external:['node:crypto'],
 target:'es2022',legalComments:'none',
 banner:{js:'// GENERATED by tools/build-online.mjs from the existing co-op engine. Do not edit.'},
 logLevel:'silent',write:false,
});
if(coopBuilt.outputFiles.length!==1)throw Error('Unexpected coop bundle output count');
const coopCheckedIn=readFileSync(coopOutput,'utf8'),coopRebuilt=coopBuilt.outputFiles[0].text;
if(coopCheckedIn!==coopRebuilt){
 let offset=0;while(offset<Math.min(coopCheckedIn.length,coopRebuilt.length)&&coopCheckedIn[offset]===coopRebuilt[offset])offset++;
 console.error('Co-op Edge difference:',{onDiskLength:coopCheckedIn.length,rebuiltLength:coopRebuilt.length,offset});
 console.error('On disk:',JSON.stringify(coopCheckedIn.slice(Math.max(0,offset-90),offset+170)));
 console.error('Expected:',JSON.stringify(coopRebuilt.slice(Math.max(0,offset-90),offset+170)));
 console.error('FAIL: generated co-op Edge bundle is out of sync with the shared engine.');
 process.exitCode=1;
}else console.log('PASS: committed coop Edge bundle exactly matches canonical shared game engine.');


// One-time trusted branch repair for generated artifacts. This branch-only
// section is removed before merge; normal CI always remains read-only.
// The generated bytes are obtained from the canonical esbuild invocations above.
// Never run for forks, main, or unrelated pull requests.
if(
  process.env.GITHUB_ACTIONS==='true'
  &&process.env.GITHUB_EVENT_NAME==='pull_request'
  &&process.env.GITHUB_REPOSITORY==='elroynbenjamins/Veldryn'
  &&process.env.GITHUB_HEAD_REF==='fix/tools-inspect-and-timed-forging-20261121'
  &&(checkedIn!==rebuilt||coopCheckedIn!==coopRebuilt)
){
  writeFileSync(output,rebuilt);
  writeFileSync(coopOutput,coopRebuilt);
  const run=(...args)=>execFileSync('git',args,{cwd:root,stdio:'inherit'});
  run('config','user.name','github-actions[bot]');
  run('config','user.email','41898282+github-actions[bot]@users.noreply.github.com');
  run('add','backend/supabase/functions/gameplay/index.ts','backend/supabase/functions/coop/index.ts');
  run('commit','-m','build(edge): synchronize canonical generated bundles for timed tool crafting');
  try{
    run('push','origin','HEAD:refs/heads/fix/tools-inspect-and-timed-forging-20261121');
    console.log('Generated Edge artifacts committed; a fresh PR run will verify exact parity.');
  }catch(error){
    console.error('Generated Edge bundles are correct but branch push was not authorized; no release artifact has been merged.',error);
  }
  process.exitCode=1;
}
