const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,'src',p),'utf8');
const browser=read('components/coop/CoopDungeonBrowser.tsx');
const screen=read('screens/CoopExpeditionScreen.tsx');
const run=read('components/coop/CoopRunOverview.tsx');
const route=read('components/coop/DungeonRouteChoices.tsx');
const stage=read('components/coop/DungeonCombatStage.tsx');
const board=read('components/coop/CoopLiveRecruitmentBoard.tsx');
const live=fs.readFileSync(path.join(root,'../../backend/online/live-runtime.ts'),'utf8');
assert(browser.includes('onBack={onBack} backLabel={a("Back")}'),'Dungeon browser must offer a real close/back action');
assert(browser.includes('onQuickMatch?<FantasyPanel variant="selected"'),'Live Quick Match should be the primary option');
assert(browser.includes("mode==='live'&&liveTools?"),'Advanced group search remains accessible');
assert(browser.includes("mode==='qmode'&&echoTools?"),'Echo sharing must not crowd primary browsing');
assert(browser.includes('NPC or Echo allies fill the missing roles'),'Solo ally description must account for NPC fallback');
assert(board.includes('showQuickMatch?<FantasyPanel'),'Optional group finder must avoid duplicate primary quick match action');
assert(screen.includes('onQuickMatch={quickLiveMatch}'),'Quick Match must retain the existing server command');
assert(screen.includes("coopClient.quickLive("),'Live Quick Match must use the server queue');
assert(screen.includes('setMyLiveVote({runId:run.runId,decisionId:run.decisionId,optionId:nodeId})'),'Vote marker records only successful submitted Live decisions');
assert(screen.includes("myLiveVote.decisionId===run.decisionId"),'Vote marker must reset when decision changes');
assert(screen.includes('const result=voting?await coopClient.vote('),'Votes must use real Live server command');
assert(run.indexOf('<DungeonRouteChoices')<run.indexOf("Party & formation"),'Current room choices must precede secondary party details');
assert(run.includes("Objectives & mechanics")&&run.includes("Party Chat"),'Details and chat remain accessible in disclosures');
assert(run.includes('<CombatTheaterModal visible')&&run.includes('<DungeonCombatStage run={run}'),'Run must retain cinematic combat for Live and Solo');
assert(stage.includes('CombatAttackSprite')&&stage.includes('CombatImpactBurst'),'Animated attack and impact effects remain in the Live combat stage');
assert(route.includes('option.votes??0'),'Live vote totals derive from server options');
assert(route.includes('myVotedNodeId===option.nodeId'),'Player portrait must appear only on their recorded route');
assert(live.includes('votes:decision.votes[String(node.nodeId)]??0'),'Backend owns displayed Live vote totals');
console.log('PASS dungeon flows: navigation, Live voting, NPC clarity, cinematic combat and advanced disclosures');
