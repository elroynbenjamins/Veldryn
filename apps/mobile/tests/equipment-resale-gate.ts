import {EQUIPMENT_RESALE_UPLIFT_RELEASED} from '../src/core/release-flags';
import {EQUIPMENT_FORGE_SELL_REFUND_RATE,itemVendorSellGold} from '../src/core/equipment-vendor-value';
import {V33_EQUIPMENT_RECIPES} from '../src/content/equipment-recipes-v33';
import {ITEMS,itemDef} from '../src/content/items';
import {createCharacter,newGame,sellItem,sellBankItem} from '../src/core/game';
const check=(value:unknown,message:string)=>{if(!value)throw new Error(message);};
const recipe=V33_EQUIPMENT_RECIPES.find(row=>row.output.itemId==='T1P_001');
if(!recipe)throw new Error('Missing T1P_001 recipe');
const gear=itemDef(recipe.output.itemId);
const nonGear=ITEMS.find(item=>item.type!=='gear'&&item.value>0);
if(!nonGear)throw new Error('Missing non-equipment fixture');
check(EQUIPMENT_RESALE_UPLIFT_RELEASED===false,'Resale uplift must remain disabled pending Edge and staging parity');
check(itemVendorSellGold(gear)===gear.value,'Release-disabled vendor price must equal current server settlement');
check(itemVendorSellGold(gear,false)===gear.value,'Explicitly disabled vendor quote must be unchanged');
check(itemVendorSellGold(gear,true)===Math.max(gear.value,Math.round(recipe.gold*EQUIPMENT_FORGE_SELL_REFUND_RATE)),'Opt-in Forge quote uses the gated 40% refund with authored floor');
check(itemVendorSellGold(nonGear,true)===nonGear.value,'Non-equipment vendor prices do not change');
let state=createCharacter(newGame(0),'BASTION','Vendor Gate QA');
if(!state.character)throw new Error('Expected character');
state={...state,inventory:{...state.inventory,stacks:[...state.inventory.stacks,{itemId:gear.id,quantity:2}]},bank:{...state.bank,stacks:[...state.bank.stacks,{itemId:gear.id,quantity:2}]}};
const beforeGold=state.character.gold,bankGold=state.bank.gold??0;
const sold=sellItem(state,gear.id,1);
check(sold.character!.gold-beforeGold===gear.value,'Current Inventory settlement matches disabled vendor quote');
check(sold.inventory.stacks.some(row=>row.itemId===gear.id&&row.quantity===1),'Inventory sale consumes precisely one item');
check(state.character.gold===beforeGold,'Inventory sale never mutates input state');
const bankSold=sellBankItem(state,gear.id,1);
check((bankSold.bank.gold??0)-bankGold===gear.value,'Bank sale credits Bank, matching the disabled vendor quote');
check(bankSold.character!.gold===beforeGold,'Bank sale never credits carried Gold');
console.log('PASS default-off equipment resale uplift, conditional Forge quote, unchanged non-gear prices and Bank/Inventory preview parity');
