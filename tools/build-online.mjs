import {createRequire} from 'node:module';
import {promises as fs} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {liveEdgeCombatV2IsolationPlugin,assertLegacyEdgeIsolation} from './combat-v2-live-edge-isolation.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'backend/package.json'));
// Keep source labels deterministic regardless of where this tool was invoked.
const backendRoot=path.join(root,'backend');
const bundles=[
 {entry:'backend/online/edge.ts',output:'backend/supabase/functions/gameplay/index.ts',
  label:'shared, tested game engine'},
 {entry:'backend/online/coop-edge.ts',output:'backend/supabase/functions/coop/index.ts',
  label:'existing co-op engine'},
];
// Check BOTH bundles before writing EITHER generated production artifact.
// The private Combat 2.0 TypeScript backend tests still use the real V2 code.
const prepared=[];
for(const bundle of bundles){
 const result=await require('esbuild').build({
  absWorkingDir:backendRoot,
  entryPoints:[path.join(root,bundle.entry)],
  outfile:path.join(root,bundle.output),
  bundle:true,format:'esm',platform:'neutral',external:['node:crypto'],
  target:'es2022',legalComments:'none',write:false,metafile:true,
  plugins:[liveEdgeCombatV2IsolationPlugin()],
  banner:{js:`// GENERATED by tools/build-online.mjs from the ${bundle.label}. Do not edit.`},
  logLevel:'info',
 });
 const audit=assertLegacyEdgeIsolation(result,bundle.output);
 if(result.outputFiles.length!==1)
  throw Error('unexpected_edge_output_count:'+bundle.output);
 prepared.push({target:path.join(root,bundle.output),
  contents:result.outputFiles[0].contents,audit});
}
// Stage BOTH outputs before replacing EITHER production artifact. A failed
// compilation or disk write cannot leave only one newly generated function.
const staged=[];
try{
 for(const [index,item] of prepared.entries()){
  const temp=item.target+'.combat-v2-isolation-'+process.pid+'-'+index+'.tmp';
  await fs.writeFile(temp,item.contents);
  staged.push({...item,temp});
 }
 for(const item of staged){
  await fs.rename(item.temp,item.target);
  console.log('Legacy Edge bundle verified:',item.audit);
 }
}finally{
 await Promise.all(staged.map(item=>fs.rm(item.temp,{force:true})));
}
